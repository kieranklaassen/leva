# frozen_string_literal: true

# Seeds the "Cora Email Routing (Inbox vs Briefed)" Leva dataset: realistic
# emails labeled with BOTH the category AND the routing decision — whether the
# email should hit the INBOX (needs you now), be BRIEFED (you should know, no
# action), or be ARCHIVED (spam). Use it to fine-tune a model that makes Cora's
# "should this be briefed?" decision in one shot.
#
# The routing rule (derived from Cora's category -> action mapping):
#   inbox    = important_draft, important_sop, important_context, timely
#   briefed  = important_info, action, promotion, newsletter, comments,
#              payments, calendar, packages, other
#   archived = spam
# (custom categories carry their own chosen routing)
#
# Run (from the Leva repo root):
#   cd test/dummy && bin/rails runner ../../script/datasets/seed_routing_dataset.rb
# Options (env): COUNT (default 1000), SEED (default 42), DATASET_NAME.
#
# Ground truth per record (EmailRoutingSample#ground_truth):
#   {"category":"promotion","routing":"briefed"}

require_relative "email_corpus"

count = Integer(ENV.fetch("COUNT", 1000))
seed  = Integer(ENV.fetch("SEED", 42))
name  = ENV.fetch("DATASET_NAME", "Cora Email Routing (Inbox vs Briefed)")

# Idempotent: drop any prior version of this dataset and its email records.
if (old = Leva::Dataset.find_by(name: name))
  ids = old.dataset_records.where(recordable_type: %w[EmailSample EmailRoutingSample]).pluck(:recordable_id)
  old.destroy
  EmailSample.where(id: ids).delete_all
  puts "Replaced existing dataset '#{name}' (removed #{ids.size} old records)."
end

dataset = Leva::Dataset.create!(
  name: name,
  description: "Email -> {category, routing}. #{count} realistic emails labeled with the Cora category " \
               "and the inbox/briefed/archived decision. Ground truth = JSON {category, routing}. " \
               "Generated by script/datasets/seed_routing_dataset.rb (seed #{seed})."
)

emails = EmailCorpus.generate(total: count, seed: seed)

ActiveRecord::Base.transaction do
  emails.each do |e|
    sample = EmailRoutingSample.create!(
      from: e[:from], from_name: e[:from_name], subject: e[:subject],
      body: e[:body], category: e[:category], routing: e[:routing]
    )
    dataset.add_record(sample)
  end
end

scope = EmailSample.where(id: dataset.dataset_records.select(:recordable_id))
puts "✓ Dataset '#{dataset.name}' (id=#{dataset.id}) — #{dataset.dataset_records.count} records"
puts "  Routing balance: #{scope.group(:routing).count}"
puts "  Categories: #{scope.group(:category).count.size}"
puts "  Example ground truth: #{dataset.dataset_records.first.recordable.ground_truth}"
puts "  Fine-tune it from the dataset page, or export with Leva::JsonlExporter.new(Leva::Dataset.find(#{dataset.id})).to_jsonl"
