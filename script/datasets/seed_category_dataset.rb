# frozen_string_literal: true

# Seeds the "Cora Email Categorization" Leva dataset: realistic emails labeled
# with their Cora category (the slug to predict). Use it to fine-tune a model
# that classifies an email into one of Cora's categories.
#
# Run (from the Leva repo root):
#   cd test/dummy && bin/rails runner ../../script/datasets/seed_category_dataset.rb
# Options (env): COUNT (default 1000), SEED (default 42), DATASET_NAME.
#
# Ground truth per record (EmailSample#ground_truth): the category slug, e.g. "promotion".

require_relative "email_corpus"

count = Integer(ENV.fetch("COUNT", 1000))
seed  = Integer(ENV.fetch("SEED", 42))
name  = ENV.fetch("DATASET_NAME", "Cora Email Categorization")

# Idempotent: drop any prior version of this dataset and its email records.
if (old = Leva::Dataset.find_by(name: name))
  ids = old.dataset_records.where(recordable_type: %w[EmailSample EmailRoutingSample]).pluck(:recordable_id)
  old.destroy
  EmailSample.where(id: ids).delete_all
  puts "Replaced existing dataset '#{name}' (removed #{ids.size} old records)."
end

dataset = Leva::Dataset.create!(
  name: name,
  description: "Email -> Cora category. #{count} realistic emails across Cora's 14 default categories " \
               "plus example custom categories. Ground truth = category slug. " \
               "Generated by script/datasets/seed_category_dataset.rb (seed #{seed})."
)

emails = EmailCorpus.generate(total: count, seed: seed)

ActiveRecord::Base.transaction do
  emails.each do |e|
    sample = EmailSample.create!(
      from: e[:from], from_name: e[:from_name], subject: e[:subject],
      body: e[:body], category: e[:category], routing: e[:routing]
    )
    dataset.add_record(sample)
  end
end

balance = EmailSample.where(id: dataset.dataset_records.select(:recordable_id)).group(:category).count
puts "✓ Dataset '#{dataset.name}' (id=#{dataset.id}) — #{dataset.dataset_records.count} records"
puts "  Categories (#{balance.size}): #{balance.sort.to_h}"
puts "  Example ground truth: #{dataset.dataset_records.first.recordable.ground_truth.inspect}"
puts "  Fine-tune it from the dataset page, or export with Leva::JsonlExporter.new(Leva::Dataset.find(#{dataset.id})).to_jsonl"
